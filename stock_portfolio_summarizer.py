# Helper function for consistent chart styling
def style_chart(ax, title, xlabel, ylabel):
    """Apply consistent professional styling to charts."""
    ax.set_title(title, fontsize=14, fontweight='bold', pad=15, color=COLORS['dark_grey'])
    ax.set_xlabel(xlabel, fontsize=11, fontweight='bold', color=COLORS['dark_grey'])
    ax.set_ylabel(ylabel, fontsize=11, fontweight='bold', color=COLORS['dark_grey'])
    ax.grid(True, linestyle='-', alpha=0.2, color=COLORS['grid_grey'])
    ax.set_axisbelow(True)
    for spine in ax.spines.values():
        spine.set_color(COLORS['grid_grey'])
        spine.set_linewidth(0.5)

