# Function to call Google Gemini API
def get_gemini_summary(portfolio_data_string: str) -> str:
    """
    Calls the Google Gemini API to summarize portfolio health.

    Args:
        portfolio_data_string (str): A string containing relevant portfolio data
                                     to be fed to the LLM.

    Returns:
        str: A summary of the portfolio's health generated by Gemini,
             or an error message if the API call fails.
    """
    try:
        # Choose a model. gemini-1.5-flash is generally good for speed and cost.
        # For more complex reasoning, consider gemini-1.5-pro.
        model = genai.GenerativeModel('gemini-1.5-flash')

        # Craft the prompt for the LLM
        prompt = (
            "Analyze the following stock portfolio data and provide a concise summary "
            "of its overall health, key characteristics, and any notable observations. "
            "Focus on diversification, risk (beta), potential income (dividend yield), and capitalization.\n\n"
            f"Portfolio Data:\n{portfolio_data_string}\n\n"
            "Summary:"
        )

        print("\n  Calling Google Gemini API for summary... (This may take a moment)")
        response = model.generate_content(prompt)

        # Check if the response has text content
        if response.candidates and response.candidates[0].content and response.candidates[0].content.parts:
            return response.candidates[0].content.parts[0].text
        else:
            print(f"      Warning: Gemini API returned an empty or malformed response. Debug info: {response}")
            return "Could not generate summary from Gemini API (empty response)."

    except Exception as e:
        print(f"      Error calling Google Gemini API: {type(e).__name__} - {e}")
        return "Could not get summary from Google Gemini API due to an error."

